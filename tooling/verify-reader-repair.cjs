const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const dom = new JSDOM(read('reader.html'), {url:'https://openstemlibrary.com/reader',runScripts:'outside-only'});
const w=dom.window,d=w.document;
const callbacks=[]; const mounted=[];
w.setTimeout=fn=>{callbacks.push(fn); return callbacks.length;}; w.scrollTo=()=>{};
w.SimulationEngine={initSimulation:(id,type)=>mounted.push(type)};
w.eval(read('course-data.js'));
const unit=w.COURSE_DATA.units[0];
const cards=[...d.querySelectorAll('.textbook-section-card')];
assert.equal(cards.length,unit.sections.length);
assert.equal(new Set(cards.map(c=>c.id)).size,cards.length);
cards.forEach((c,i)=>assert.equal(c.querySelector('.sec-title span:last-child').textContent,unit.sections[i].heading));
assert.equal(d.querySelectorAll('.problem-card').length,unit.problems.length);
assert.ok(unit.problems.length>0);
assert.equal([...d.querySelectorAll('h4,strong')].filter(n=>!n.textContent.trim()).length,0);
const simulations=unit.sections.flatMap(s=>s.simulation?[s.simulation]:s.simulations||[]);
for(const sim of simulations)assert.equal(d.querySelectorAll('#sim-container-'+sim).length,1);
w.eval(read('app.js').split('\nif (document.readyState === "loading")')[0]);w.startApp();
callbacks.forEach(fn=>fn());
for(const sim of simulations)assert.ok(mounted.includes(sim), `Simulation did not initialize: ${sim}`);
const btn=d.querySelector('.solution-toggle-btn,.btn-solution-toggle');
btn.click();assert.equal(btn.getAttribute('aria-expanded'),'true');
assert.ok(d.querySelector('.solution-content').classList.contains('open'));
btn.click();assert.equal(btn.getAttribute('aria-expanded'),'false');
assert.equal(d.querySelectorAll('.unit-nav-link').length,w.COURSE_DATA.units.length);
console.log(`PASS: ${cards.length} unique source sections, ${simulations.length} simulation mounts, ${unit.problems.length} worked problems, solution toggles, chapter links.`);
w.close();
