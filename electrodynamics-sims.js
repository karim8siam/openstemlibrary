// Electrodynamics Simulation Engine Suite
// High-performance 60 FPS Canvas renderers with interactive sliders and parameter controls

window.SimulationEngine = {
  activeInstances: {},

  initSimulation: function(containerId, simType) {
    const container = document.getElementById(containerId);
    if (!container) return;
    
    // Clean up existing instance
    if (this.activeInstances[containerId]) {
      this.activeInstances[containerId].destroy();
    }

    container.innerHTML = "";
    
    switch(simType) {
      case "displacement-current":
        this.activeInstances[containerId] = new DisplacementCurrentSim(container);
        break;
      case "poynting-vector":
        this.activeInstances[containerId] = new PoyntingSim(container);
        break;
      case "em-wave-3d":
        this.activeInstances[containerId] = new EMWave3DSim(container);
        break;
      case "skin-depth":
        this.activeInstances[containerId] = new SkinDepthSim(container);
        break;
      case "fresnel-reflection":
        this.activeInstances[containerId] = new FresnelSim(container);
        break;
      case "waveguide-modes":
        this.activeInstances[containerId] = new WaveguideSim(container);
        break;
      case "dipole-radiation":
        this.activeInstances[containerId] = new DipoleRadiationSim(container);
        break;
      case "scattering-simulator":
        this.activeInstances[containerId] = new ScatteringSim(container);
        break;
      case "drude-lorentz":
        this.activeInstances[containerId] = new DrudeLorentzSim(container);
        break;
      case "radiation-pressure-sim":
        this.activeInstances[containerId] = new RadiationPressureSim(container);
        break;
      case "plasma-cutoff-sim":
        this.activeInstances[containerId] = new PlasmaCutoffSim(container);
        break;
      case "snell-refraction-sim":
        this.activeInstances[containerId] = new SnellRefractionSim(container);
        break;
      case "cavity-resonator-sim":
        this.activeInstances[containerId] = new CavityResonatorSim(container);
        break;
      case "retarded-potential-sim":
        this.activeInstances[containerId] = new RetardedPotentialSim(container);
        break;
      case "antenna-radiation-sim":
        this.activeInstances[containerId] = new AntennaRadiationSim(container);
        break;
      case "polarization-sky-sim":
        this.activeInstances[containerId] = new PolarizationSkySim(container);
        break;
      case "sellmeier-prism-sim":
        this.activeInstances[containerId] = new SellmeierPrismSim(container);
        break;
      default:
        console.warn("Unknown simulation type:", simType);
    }
  }
};

