class EMWave3DSim {
  constructor(container) {
    this.container = container;
    this.wavelength = 180;
    this.animId = null;
    this.t = 0;

    this.renderDOM();
    this.initCanvas();
    this.startLoop();
  }

  renderDOM() {
    this.container.innerHTML = `
      <div class="sim-wrapper">
        <div class="sim-header">
          <div class="sim-title">
            <span class="sim-badge">Simulation 2.1</span>
            <strong>3D Transverse Electromagnetic Wave: Orthogonal $\\mathbf{E}$ (Cyan) and $\\mathbf{B}$ (Yellow)</strong>
          </div>
          <div class="slider-control-group">
            <label>Wavelength $\\lambda$: <strong id="em-wl-val">180 px</strong></label>
            <input type="range" id="em-wl-slider" min="100" max="280" value="180" class="range-slider">
          </div>
        </div>
        <div class="canvas-container">
          <canvas id="em-canvas" width="760" height="340"></canvas>
          <div class="sim-watermark">OpenSTEM • Electrodynamics • Protected</div>
        </div>
        <div class="sim-footer">
          <div class="sim-hint">
            💡 Notice that $\\mathbf{E}$ and $\\mathbf{B}$ oscillate strictly perpendicular to each other and to the propagation axis $+z$, in perfect phase with speed $c = \\omega / k = 1/\\sqrt{\\mu_0\\epsilon_0}$.
          </div>
        </div>
      </div>
    `;

    document.getElementById("em-wl-slider").oninput = (e) => {
      this.wavelength = parseFloat(e.target.value);
      document.getElementById("em-wl-val").innerText = this.wavelength + " px";
    };
  }

  initCanvas() {
    this.canvas = document.getElementById("em-canvas");
    this.ctx = this.canvas.getContext("2d");
  }

  startLoop() {
    const loop = () => {
      this.t += 0.05;
      this.draw();
      this.animId = requestAnimationFrame(loop);
    };
    this.animId = requestAnimationFrame(loop);
  }

  draw() {
    const { ctx, canvas } = this;
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    ctx.fillStyle = "#0a0e19";
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    const originY = 170;
    const originX = 50;
    const endX = canvas.width - 50;

    // Propagation Axis (z-axis)
    ctx.strokeStyle = "#475569";
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(originX, originY);
    ctx.lineTo(endX, originY);
    ctx.stroke();

    ctx.fillStyle = "#94a3b8";
    ctx.font = "12px Inter, sans-serif";
    ctx.fillText("Propagation Axis +z → (Speed c)", endX - 160, originY - 12);

    const k = (2 * Math.PI) / this.wavelength;
    const ampE = 80;
    const ampB = 45; // projected at oblique angle for 3D depth

    // Draw Magnetic Field Vectors B (Yellow, tilted perspective 45 deg)
    ctx.strokeStyle = "#fbbf24";
    ctx.lineWidth = 1.5;
    for (let x = originX; x <= endX; x += 18) {
      const z = x - originX;
      const val = Math.sin(k * z - this.t);
      const bLen = val * ampB;

      const px = x - bLen * 0.7;
      const py = originY + bLen * 0.5;

      ctx.beginPath();
      ctx.moveTo(x, originY);
      ctx.lineTo(px, py);
      ctx.stroke();

      // Vector head dot
      ctx.fillStyle = "#fbbf24";
      ctx.beginPath();
      ctx.arc(px, py, 2.5, 0, Math.PI * 2);
      ctx.fill();
    }

    // Draw Electric Field Vectors E (Cyan, vertical)
    ctx.strokeStyle = "#38bdf8";
    ctx.lineWidth = 1.8;
    for (let x = originX; x <= endX; x += 18) {
      const z = x - originX;
      const val = Math.sin(k * z - this.t);
      const eLen = val * ampE;

      ctx.beginPath();
      ctx.moveTo(x, originY);
      ctx.lineTo(x, originY - eLen);
      ctx.stroke();

      // Vector head dot
      ctx.fillStyle = "#38bdf8";
      ctx.beginPath();
      ctx.arc(x, originY - eLen, 2.5, 0, Math.PI * 2);
      ctx.fill();
    }

    // Envelope curves
    ctx.strokeStyle = "rgba(56, 189, 248, 0.4)";
    ctx.lineWidth = 2;
    ctx.beginPath();
    for (let x = originX; x <= endX; x++) {
      const z = x - originX;
      const y = originY - Math.sin(k * z - this.t) * ampE;
      if (x === originX) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.stroke();

    ctx.fillStyle = "#38bdf8";
    ctx.fillText("Electric Field E (Vertical)", 60, 45);
    ctx.fillStyle = "#fbbf24";
    ctx.fillText("Magnetic Field B (Horizontal Transverse)", 60, 68);
  }

  destroy() {
    if (this.animId) cancelAnimationFrame(this.animId);
  }
}

