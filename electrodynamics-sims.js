class SkinDepthSim {
  constructor(container) {
    this.container = container;
    this.sigma = 40; // conductivity slider
    this.animId = null;
    this.t = 0;

    this.renderDOM();
    this.initCanvas();
    this.startLoop();
  }

  renderDOM() {
    this.container.innerHTML = `
      <div class="sim-wrapper">
        <div class="sim-header">
          <div class="sim-title">
            <span class="sim-badge">Simulation 2.2</span>
            <strong>Electromagnetic Wave Attenuation & Skin Depth: $\\delta = \\sqrt{\\frac{2}{\\mu \\sigma \\omega}}$</strong>
          </div>
          <div class="slider-control-group">
            <label>Conductivity $\\sigma$: <strong id="sd-sig-val">Medium Conductor</strong></label>
            <input type="range" id="sd-sig-slider" min="10" max="90" value="40" class="range-slider">
          </div>
        </div>
        <div class="canvas-container">
          <canvas id="sd-canvas" width="760" height="300"></canvas>
          <div class="sim-watermark">OpenSTEM • Electrodynamics • Protected</div>
        </div>
        <div class="sim-metrics-grid">
          <div class="metric-card">
            <div class="metric-label">Skin Depth $\\delta$</div>
            <div class="metric-value text-emerald" id="metric-delta">45 mm</div>
          </div>
          <div class="metric-card">
            <div class="metric-label">Phase Shift in Conductor</div>
            <div class="metric-value text-amber">45° Lag (B behind E)</div>
          </div>
        </div>
      </div>
    `;

    document.getElementById("sd-sig-slider").oninput = (e) => {
      this.sigma = parseFloat(e.target.value);
      const label = this.sigma < 30 ? "Poor Conductor" : (this.sigma < 70 ? "Good Conductor" : "Metal (Copper-like)");
      document.getElementById("sd-sig-val").innerText = label;
      this.updateMetrics();
    };
    this.updateMetrics();
  }

  updateMetrics() {
    const delta = (240 / Math.sqrt(this.sigma)).toFixed(1);
    document.getElementById("metric-delta").innerText = delta + " mm";
  }

  initCanvas() {
    this.canvas = document.getElementById("sd-canvas");
    this.ctx = this.canvas.getContext("2d");
  }

  startLoop() {
    const loop = () => {
      this.t += 0.06;
      this.draw();
      this.animId = requestAnimationFrame(loop);
    };
    this.animId = requestAnimationFrame(loop);
  }

  draw() {
    const { ctx, canvas } = this;
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    ctx.fillStyle = "#090d18";
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    const boundaryX = 280;
    const midY = 150;

    // Draw Conductor Shading (Right Region)
    ctx.fillStyle = "rgba(30, 41, 59, 0.7)";
    ctx.fillRect(boundaryX, 0, canvas.width - boundaryX, canvas.height);

    // Boundary Line
    ctx.strokeStyle = "#e2e8f0";
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(boundaryX, 0);
    ctx.lineTo(boundaryX, canvas.height);
    ctx.stroke();

    ctx.fillStyle = "#94a3b8";
    ctx.font = "12px Inter, sans-serif";
    ctx.fillText("Vacuum / Air (σ = 0)", 80, 30);
    ctx.fillText("Conducting Medium (Conductivity σ)", boundaryX + 30, 30);

    // Baseline
    ctx.strokeStyle = "#334155";
    ctx.beginPath();
    ctx.moveTo(20, midY);
    ctx.lineTo(canvas.width - 20, midY);
    ctx.stroke();

    const amp = 85;
    const k1 = 0.05;
    const kappa = 0.012 * Math.sqrt(this.sigma);
    const skinDepthPx = 1 / kappa;

    // Plot Left Region: Undamped Incident Wave
    ctx.strokeStyle = "#38bdf8";
    ctx.lineWidth = 2.5;
    ctx.beginPath();
    for (let x = 30; x <= boundaryX; x++) {
      const y = midY - amp * Math.sin(k1 * (x - boundaryX) - this.t);
      if (x === 30) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }

    // Plot Right Region: Exponentially Damped Wave
    for (let x = boundaryX; x <= canvas.width - 30; x++) {
      const dist = x - boundaryX;
      const decay = Math.exp(-kappa * dist);
      const y = midY - amp * decay * Math.sin(k1 * 1.8 * dist - this.t);
      ctx.lineTo(x, y);
    }
    ctx.stroke();

    // Draw Exponential Decay Envelope
    ctx.strokeStyle = "rgba(244, 63, 94, 0.6)";
    ctx.setLineDash([5, 4]);
    ctx.beginPath();
    for (let x = boundaryX; x <= canvas.width - 30; x++) {
      const dist = x - boundaryX;
      const decay = Math.exp(-kappa * dist);
      const y = midY - amp * decay;
      if (x === boundaryX) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.stroke();
    ctx.setLineDash([]);

    // Skin Depth Marker
    const markerX = boundaryX + skinDepthPx;
    if (markerX < canvas.width - 30) {
      ctx.strokeStyle = "#10b981";
      ctx.lineWidth = 1.5;
      ctx.setLineDash([4, 4]);
      ctx.beginPath();
      ctx.moveTo(markerX, 40);
      ctx.lineTo(markerX, canvas.height - 30);
      ctx.stroke();
      ctx.setLineDash([]);

      ctx.fillStyle = "#10b981";
      ctx.fillText("Skin Depth δ (1/e ≈ 37%)", markerX + 6, 75);
    }
  }

  destroy() {
    if (this.animId) cancelAnimationFrame(this.animId);
  }
}

