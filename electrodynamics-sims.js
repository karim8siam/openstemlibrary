// 1. Displacement Current & Induced B-Field
// ==========================================
class DisplacementCurrentSim {
  constructor(container) {
    this.container = container;
    this.current = 2.0; // Amperes
    this.t = 0;
    this.animId = null;

    this.renderDOM();
    this.initCanvas();
    this.startLoop();
  }

  renderDOM() {
    this.container.innerHTML = `
      <div class="sim-wrapper">
        <div class="sim-header">
          <div class="sim-title">
            <span class="sim-badge">Simulation 1.1</span>
            <strong>Capacitor Displacement Current $J_d = \\epsilon_0 \\frac{\\partial E}{\\partial t}$ & Induced Magnetic Field</strong>
          </div>
          <div class="slider-control-group">
            <label>Charging Current $I$: <strong id="dc-i-val">2.0 A</strong></label>
            <input type="range" id="dc-i-slider" min="5" max="50" value="20" class="range-slider">
          </div>
        </div>
        <div class="canvas-container">
          <canvas id="dc-canvas" width="760" height="340"></canvas>
          <div class="sim-watermark">OpenSTEM • Electrodynamics • Protected</div>
        </div>
        <div class="sim-footer">
          <div class="sim-hint">
            💡 Cyan arrows: Electric field $\\mathbf{E}$ between plates. Orange circular loops: Induced magnetic field $\\mathbf{B}$ generated by the time-varying electric flux (Maxwell's displacement current).
          </div>
        </div>
      </div>
    `;

    document.getElementById("dc-i-slider").oninput = (e) => {
      this.current = (parseFloat(e.target.value) / 10).toFixed(1);
      document.getElementById("dc-i-val").innerText = this.current + " A";
    };
  }

  initCanvas() {
    this.canvas = document.getElementById("dc-canvas");
    this.ctx = this.canvas.getContext("2d");
  }

  startLoop() {
    const loop = () => {
      this.t += 0.03 * (this.current / 2);
      this.draw();
      this.animId = requestAnimationFrame(loop);
    };
    this.animId = requestAnimationFrame(loop);
  }

  draw() {
    const { ctx, canvas } = this;
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    ctx.fillStyle = "#090d18";
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    const midY = 170;
    const p1X = 260;
    const p2X = 500;
    const plateH = 160;

    // Draw Incoming Wire Left
    ctx.strokeStyle = "#94a3b8";
    ctx.lineWidth = 6;
    ctx.beginPath();
    ctx.moveTo(30, midY);
    ctx.lineTo(p1X, midY);
    ctx.stroke();

    // Draw Outgoing Wire Right
    ctx.beginPath();
    ctx.moveTo(p2X, midY);
    ctx.lineTo(canvas.width - 30, midY);
    ctx.stroke();

    // Conduction current arrows
    ctx.fillStyle = "#38bdf8";
    ctx.font = "12px Inter, sans-serif";
    ctx.fillText(`Conduction Current I = ${this.current} A →`, 60, midY - 15);
    ctx.fillText(`→ I = ${this.current} A`, p2X + 60, midY - 15);

    // Capacitor Plate 1 (Left, +Q)
    ctx.fillStyle = "rgba(56, 189, 248, 0.25)";
    ctx.strokeStyle = "#38bdf8";
    ctx.lineWidth = 4;
    ctx.fillRect(p1X - 8, midY - plateH/2, 16, plateH);
    ctx.strokeRect(p1X - 8, midY - plateH/2, 16, plateH);
    ctx.fillStyle = "#38bdf8";
    ctx.fillText("+Q (Positive Plate)", p1X - 60, midY - plateH/2 - 12);

    // Capacitor Plate 2 (Right, -Q)
    ctx.fillStyle = "rgba(244, 63, 94, 0.25)";
    ctx.strokeStyle = "#f43f5e";
    ctx.lineWidth = 4;
    ctx.fillRect(p2X - 8, midY - plateH/2, 16, plateH);
    ctx.strokeRect(p2X - 8, midY - plateH/2, 16, plateH);
    ctx.fillStyle = "#f43f5e";
    ctx.fillText("-Q (Negative Plate)", p2X - 10, midY - plateH/2 - 12);

    // Electric Field Lines (Cyan horizontal arrows)
    ctx.strokeStyle = "#38bdf8";
    ctx.lineWidth = 2;
    for (let y = midY - 60; y <= midY + 60; y += 30) {
      ctx.beginPath();
      ctx.moveTo(p1X + 10, y);
      ctx.lineTo(p2X - 10, y);
      ctx.stroke();

      // Arrowhead
      ctx.beginPath();
      ctx.moveTo(p2X - 18, y - 5);
      ctx.lineTo(p2X - 10, y);
      ctx.lineTo(p2X - 18, y + 5);
      ctx.stroke();
    }
    ctx.fillStyle = "#38bdf8";
    ctx.fillText("Electric Field E(t)", 340, midY - 70);

    // Circular Induced Magnetic Field Loops (Perspective Ellipses)
    const gapCenterX = (p1X + p2X) / 2;
    ctx.strokeStyle = "#f59e0b";
    ctx.lineWidth = 2;

    const numLoops = 3;
    for (let l = 1; l <= numLoops; l++) {
      const rx = 18 + l * 20;
      const ry = 28 + l * 26;

      ctx.beginPath();
      ctx.ellipse(gapCenterX, midY, rx, ry, 0, 0, Math.PI * 2);
      ctx.stroke();

      // Animated circulating dots on B-field loop
      const angle = this.t + (l * 0.8);
      const bx = gapCenterX + rx * Math.cos(angle);
      const by = midY + ry * Math.sin(angle);

      ctx.fillStyle = "#fbbf24";
      ctx.beginPath();
      ctx.arc(bx, by, 3.5, 0, Math.PI * 2);
      ctx.fill();
    }

    ctx.fillStyle = "#f59e0b";
    ctx.fillText("Induced Magnetic Field B(r)", gapCenterX - 75, midY + plateH/2 + 25);
    ctx.fillText(`J_d = ε₀ ∂E/∂t = ${this.current} A / Area`, gapCenterX - 70, midY + plateH/2 + 42);
  }

  destroy() {
    if (this.animId) cancelAnimationFrame(this.animId);
  }
}

